-- ============================================================================
-- 迁移：V709__seg7_user_region_options.sql
-- 所属段：第 7 段（运营与治理收口）——尾巴的补登记
-- 做什么：补 1 个 sys_config 键 `user.region_options`，值是 JSON 数组字符串，
--         作为「用户所在地区」枚举的**唯一来源**，供注册页渲染选择器 + 服务端校验白名单。
--
-- 为什么算「尾巴的补登记」而不是新需求：
--   `app_user.region` 是 V707 建的列，但当时**没有任何采集入口**，恒为 NULL——
--   实测后果是 A-02 看板「地区分布」只有一项「其他」，按地区发公告必然 0 人且不报错。
--   负责人 2026-11-09 拍板选「注册页采集」（不选资料页选填，理由：选填覆盖率太低，
--   会让地区功能形同虚设）。本迁移与注册链路改造一起把入口接上。
--   V707 已执行，按《数据表规范》§七「已执行的迁移一律不改」，所以单独开一个迁移。
--
-- 为什么枚举放配置而不是写死在代码里（**本迁移的关键设计点**）：
--   `["伊宁市","奎屯市","霍尔果斯市","伊宁县","察布查尔锡伯自治县","霍城县","巩留县",
--     "新源县","昭苏县","特克斯县","尼勒克县","其他"]`
--   = 伊犁哈萨克自治州直辖的 11 个县级行政区 + 「其他」。
--   **塔城地区、阿勒泰地区暂不列入**：两者同属伊犁州管辖，但历史上是独立地区、
--   业务上也是独立片区，是否纳入待负责人再定。
--   放进 sys_config 之后，将来加一个县只需要在 PC 系统参数页改配置，
--   **不动代码、不发版**——这正是「枚举来源单一」想要的。
--   代码里只留一份兜底列表（配置被误删/写坏时注册不能全挂），见 `RegionOptionsService`。
--
-- 幂等：ON DUPLICATE KEY UPDATE，但**不更新 config_value**——
--   地区清单是运营会在 PC 上改的值（加县/改称谓），重跑迁移把它冲回默认值，
--   等于迁移脚本偷偷回滚了运营动作。只更新 value_type / category / remark / editable。
--
-- 授权：本迁移只加 sys_config 行，**不建表、不改列**，因此不需要补表级授权
--   （deploy/sync-db-grants.ps1 只对新表有意义）。
-- ============================================================================

INSERT INTO sys_config (config_key, config_value, value_type, category, remark, editable, created_at, updated_at) VALUES
('user.region_options',
 '["伊宁市","奎屯市","霍尔果斯市","伊宁县","察布查尔锡伯自治县","霍城县","巩留县","新源县","昭苏县","特克斯县","尼勒克县","其他"]',
 'json', 'user',
 '用户所在地区可选值（JSON 数组字符串）；注册页据此渲染选择器，服务端据此校验白名单。加县只改这里，不用发版；塔城/阿勒泰两地区暂不列入',
 1, UTC_TIMESTAMP(), UTC_TIMESTAMP())
ON DUPLICATE KEY UPDATE
  value_type = VALUES(value_type),
  category   = VALUES(category),
  remark     = VALUES(remark),
  editable   = VALUES(editable),
  updated_at = UTC_TIMESTAMP();
