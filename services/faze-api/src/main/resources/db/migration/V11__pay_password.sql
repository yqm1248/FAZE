-- ============================================================================
-- V11 · 支付密码字段（第 1 段 E1）
--
-- 依据：《第 1 段工作流》E1 第 1 条——「支付密码单独存（加字段 pay_password，BCrypt）」，
--   不是复用登录密码字段，也不是新建表。
--
-- 为什么必须单独一个字段而不是共用 password_hash：
--   1. 登录密码和支付密码是**两种用途不同的凭证**，共用一个哈希时改一个必然静默改掉另一个；
--   2. 支付密码是 6 位纯数字（100 万种组合），密码策略与登录密码（≥8 位含字母）完全不同，
--      共用字段会让强度校验无处安放；
--   3. 锁定策略也不同：登录锁定 5 次/15 分钟，支付密码锁定 5 次/30 分钟。
--
-- NULL 表示「尚未设置支付密码」，与「设置了空密码」必须区分开——
-- 后者会让任何人都能通过支付校验。
-- ============================================================================

ALTER TABLE app_user
  ADD COLUMN pay_password VARCHAR(100) DEFAULT NULL
      COMMENT '支付密码 BCrypt 哈希（6 位数字的 BCrypt 结果）；NULL 表示未设置，禁止与登录密码共用字段' AFTER password_hash;
