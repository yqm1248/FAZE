-- ============================================================================
-- V9 · 实名认证需要身份证掩码列（第 1 段 C1）
--
-- 背景：C1 第 4 条要求「身份证号必须加密或脱敏——不得明文进日志」。
--   方案：id_card_number 存 AES-256-GCM 密文；另存 id_card_masked（形如 110***********1234）
--   供审核列表与详情展示。**列表页只读掩码列，不解密**——解密只发生在审核详情动作里。
--
-- 为什么列表页不能解密：解密密钥一旦在列表接口里被调用，就必然出现在日志/异常栈的
--   上下文里；「解密的入口越少越安全」比「每次解密后记得别打日志」可靠。
-- ============================================================================

ALTER TABLE realname_auth
  ADD COLUMN id_card_masked VARCHAR(20) DEFAULT NULL
      COMMENT '身份证号掩码（110***********1234），供列表/详情展示，禁止用于业务判断' AFTER id_card_number;
