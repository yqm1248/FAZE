-- ============================================================================
-- 迁移：V801__i18n_glossary_frozen_at.sql
-- 所属段：第 8 段（B-2 术语表冻结）
-- 做什么：给 `i18n_glossary` 加 `frozen_at` 列，并把现有 51 条术语一次性标记为已冻结。
--
-- 为什么需要这一列（不是"加着玩"）：
--   第 8 段锚点 `8-A2` 的判定口径被负责人降级为「**术语表冻结 + 机器一致性校验**」
--   （母语者签字挂 DEF-003）。工作流的验收句是「`i18n_glossary` 术语表已冻结
--   （`frozen_at` 有值）」——而本表**没有 frozen_at 列**，只有 `status`
--   （confirmed/pending，段 3 建表时只有 confirmed）。`status` 表达的是「这条术语本身
--   定没定」，无法表达「**在某个时间点，整张表被冻结，之后改动要走过审批**」。
--   两者语义不同，所以加列而不是复用 status。
--
-- 冻结的是什么（写清楚，避免误解）：
--   冻结的是**术语集合与中文源术语**（`term_key` + `source_text`）。当前 51 条全部是
--   `lang='zh-Hans'`、`target_text=''`（技术路线 §13.8：术语译文必须由母语法律译者确认，
--   **不许机翻**）。所以这次冻结**不涉及任何译文**——译文仍是待填状态，
--   补译文属 DEF-003，本段不做。
--
-- 为什么是整表一个时间戳（而不是逐条）：
--   冻结是"整张表进入冻结态"这个事件，不是 51 个独立决策。逐条时间戳会让
--   「这张表到底冻没冻」需要靠 COUNT 判断，而单列语义只要 `IS NOT NULL` 一查就清楚。
--   将来新增术语时，新行 `frozen_at` 为 NULL，即"冻结后新增、待复审"——这是有意的设计。
--
-- 不改什么：
--   1. **不改 `status`**：51 条全是 confirmed，那是段 3 灌数据时的原始状态，与冻结无关。
--   2. **不改 `target_text`**：仍是空串。**不要**为了让"术语表看起来完整"去填机翻译文
--      ——技术路线 §13.8 明文禁止，且会污染 AI 提示词与文书模板的术语来源。
--   3. 不新增表、不新增索引：全量 51~200 条，全表扫比索引快。
--
-- 影响面：
--   - 实体 `I18nGlossary` 加 `frozenAt` 字段
--   - 《数据表规范》附录 A 的 `i18n_glossary` 列清单从 10 列变 11 列
--   - `docs/facts/tables.json` 重算（列数 687 → 688）
--   - PC A-17 术语表页（本段新增）显示冻结态
-- ============================================================================

ALTER TABLE i18n_glossary
  ADD COLUMN frozen_at DATETIME NULL DEFAULT NULL
  COMMENT '术语表冻结时间（UTC）；NULL = 冻结后新增、待复审';

-- 回填：把现有 51 条标记为「随本次冻结一起生效」。
-- 用固定时刻而不是 NOW()：迁移在别人的机器上重跑时 NOW() 会变，
-- 而"什么时候冻的"是历史事实，不该随执行时间漂。
UPDATE i18n_glossary
SET frozen_at = '2026-11-13 00:00:00'
WHERE frozen_at IS NULL;
